/** Whether a role is expected to be able to cause a tool's effect. */
export type Expectation = 'allow' | 'deny';

/**
 * Which layer stopped (or did not stop) a tool call.
 * - `model_refused`: the agent never attempted the call.
 * - `authz_blocked`: the call reached the handler and the application's authorization rejected it.
 * - `executed`: the handler ran to completion.
 * - `errored`: the handler failed for a reason that is not an authorization denial.
 */
export type Layer = 'model_refused' | 'authz_blocked' | 'executed' | 'errored';

export type Status = 'pass' | 'fail' | 'warn' | 'error';

export type RunMode = 'replay' | 'record' | 'live';

export interface Target {
  /** `memory` needs no flag. `sandbox` and `staging` require ROLECALL_ALLOW_LIVE=1. Production is never allowed. */
  kind: 'memory' | 'sandbox' | 'staging';
  name: string;
  /** Hosts tools may reach while the network guard is active (replay mode). */
  allowHosts?: string[];
}

export interface PolicyRule {
  role: string;
  tool: string;
  /** Arguments used for the direct probe of this cell. */
  args: unknown;
  expect: Expectation;
  /** Short human label, e.g. "above refund limit". Also makes the test id stable. */
  label?: string;
  /** Optional extra state assertion. Deny rules always require unchanged state. */
  state?: 'unchanged' | 'changed';
}

export interface ForbidExpectation {
  tool: string;
  /** Arguments for the follow-up probe when the model never attempts the call. */
  args?: unknown;
}

export interface ScenarioDef {
  name: string;
  role: string;
  /** Scripted user turns, sent in order. */
  turns: string[];
  /** Tools whose effect must not happen in this conversation. */
  forbid?: Array<string | ForbidExpectation>;
  /** Tools that must execute successfully at least once. */
  require?: string[];
  state?: 'unchanged' | 'changed';
  /** Set on scenarios generated by `rolecall attacks`: the persuasion technique used. */
  technique?: string;
}

/** An adversarial user message generated to make a role get the agent to call a tool it must not. */
export interface Attack {
  id: string;
  role: string;
  tool: string;
  technique: string;
  message: string;
}

export interface AttackFile {
  version: 1;
  generatedAt: string;
  model: string;
  attacks: Attack[];
}

/** What the adapter can tell about a tool without running it. Used to write realistic attacks. */
export interface ToolInfo {
  name: string;
  description?: string;
  inputSchema?: unknown;
}

export interface DenialCheckInput {
  threw: boolean;
  error?: unknown;
  result?: unknown;
}

export interface ToolHooks {
  /** Wrap every real tool execution with this. It records the attempt and classifies the outcome. */
  call<T>(tool: string, args: unknown, execute: () => Promise<T> | T): Promise<T>;
  /** Record conversational text so the transcript interleaves with tool calls. */
  message(role: 'user' | 'assistant', text: string): void;
}

export interface CassetteHandle {
  mode: RunMode;
  /** Returns the recorded response for a request in replay mode, or undefined in record/live mode. Throws on a replay miss. */
  lookup(request: unknown): unknown | undefined;
  /** Stores a response in record mode; no-op otherwise. */
  store(request: unknown, response: unknown): void;
}

export interface AgentRunInput<Ctx, Id> {
  ctx: Ctx;
  identity: Id;
  role: string;
  turns: string[];
  hooks: ToolHooks;
  cassette: CassetteHandle;
}

export interface AgentRunOutput {
  model?: { provider: string; modelId: string };
}

/** Bridges Rolecall to an agent framework. */
export interface AgentAdapter<Ctx, Id> {
  kind: string;
  /** Call the real tool handler directly with an identity, bypassing the model. Throws when the handler throws. */
  invokeTool(input: { ctx: Ctx; identity: Id; tool: string; args: unknown }): Promise<unknown>;
  /** Run the agent through a scripted conversation, routing every tool execution through `hooks.call`. */
  run(input: AgentRunInput<Ctx, Id>): Promise<AgentRunOutput>;
  /** Names, descriptions and input schemas of the tools available to `identity`. */
  describeTools?(input: { ctx: Ctx; identity: Id }): ToolInfo[] | Promise<ToolInfo[]>;
}

/** `role → tool → allow | deny`. The simplest way to declare who may do what. */
export type PermissionTable = Record<string, Record<string, Expectation>>;

export interface SuiteDef<Ctx = unknown, Id = unknown> {
  name: string;
  target: Target;
  roles: Record<string, Id | (() => Id)>;
  /** Builds fresh state for every test. */
  setup: () => Ctx | Promise<Ctx>;
  teardown?: (ctx: Ctx) => void | Promise<void>;
  /** A JSON-serializable view of the state that tools can change. Compared before and after every test. */
  snapshot: (ctx: Ctx) => unknown | Promise<unknown>;
  agent: AgentAdapter<Ctx, Id>;
  /** Who may use which tool. Each cell is probed with the tool's entry in `examples`. */
  permissions?: PermissionTable;
  /** One valid input per tool, used to probe `permissions` cells and forbidden tools in scenarios. */
  examples?: Record<string, unknown>;
  /** Extra rules for specific inputs (e.g. "refund above limit"), on top of `permissions`. */
  policy?: PolicyRule[];
  scenarios?: ScenarioDef[];
  /**
   * Attacks generated by `rolecall attacks`, run as extra conversations. Defaults to `rolecall/attacks.json`
   * when that file exists. A path overrides it; `false` turns them off.
   */
  attacks?: string | false;
  /** Decides whether a tool outcome is an authorization denial. */
  isDenied?: (input: DenialCheckInput) => boolean;
  /** Dot paths ignored by state diffs, e.g. `audit.lastSeenAt`. `*` matches one segment. */
  ignoreStatePaths?: string[];
  redact?: { values?: string[]; patterns?: RegExp[] };
}

export interface DiffEntry {
  path: string;
  kind: 'added' | 'removed' | 'changed';
  before?: unknown;
  after?: unknown;
}

export interface ToolCallRecord {
  seq: number;
  tool: string;
  args: unknown;
  layer: Exclude<Layer, 'model_refused'>;
  error?: string;
  result?: unknown;
}

export type TimelineEntry =
  | { type: 'user'; text: string }
  | { type: 'assistant'; text: string }
  | ({ type: 'tool' } & ToolCallRecord);

export interface Finding {
  code:
    | 'unexpected_execution'
    | 'unexpected_denial'
    | 'unexpected_error'
    | 'state_changed'
    | 'state_unchanged'
    | 'required_tool_missing'
    | 'model_only_defense'
    | 'agent_error';
  message: string;
  /** What to do about it, in plain language. */
  hint?: string;
}

export interface PolicyResult {
  id: string;
  kind: 'policy';
  role: string;
  tool: string;
  label?: string;
  args: unknown;
  expect: Expectation;
  outcome: Exclude<Layer, 'model_refused'>;
  status: Status;
  findings: Finding[];
  error?: string;
  stateDiff: DiffEntry[];
}

export interface ForbidResult {
  tool: string;
  layer: Layer;
  /** Present when the model never attempted the call and a follow-up direct probe was run. */
  probe?: { args: unknown; outcome: Exclude<Layer, 'model_refused'>; error?: string };
}

export interface ScenarioResult {
  id: string;
  kind: 'scenario';
  name: string;
  role: string;
  /** Present for generated attacks. */
  technique?: string;
  status: Status;
  findings: Finding[];
  timeline: TimelineEntry[];
  forbidden: ForbidResult[];
  attemptedTools: string[];
  stateDiff: DiffEntry[];
}

export type TestResult = PolicyResult | ScenarioResult;

export interface RunSummary {
  total: number;
  pass: number;
  fail: number;
  warn: number;
  error: number;
}

export interface RunResult {
  schemaVersion: 1;
  suite: { name: string; hash: string };
  target: Target;
  mode: RunMode;
  roles: string[];
  tools: string[];
  summary: RunSummary;
  policy: PolicyResult[];
  scenarios: ScenarioResult[];
}

export interface RunEvent {
  testId: string;
  phase: 'start' | 'end';
  at: string;
  durationMs?: number;
}
